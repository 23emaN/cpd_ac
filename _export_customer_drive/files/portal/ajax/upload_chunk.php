<?php

/**
 * รับไฟล์ทีละก้อนแล้วประกอบ — สำหรับไฟล์ใหญ่และเน็ตที่ไม่นิ่ง
 *
 * ------------------------------------------------------------
 * เหตุผลจริงของทางนี้ไม่ใช่ "ไฟล์ใหญ่" แต่คือ "ส่งต่อจากที่ค้างได้"
 * ------------------------------------------------------------
 * ลูกค้าสแกนเอกสารจากมือถือบนเน็ต 4G ที่หลุด ๆ ติด ๆ ถ้าส่งทีเดียวจบ
 * เน็ตหลุดตอน 90% แปลว่าเริ่มใหม่ทั้งไฟล์ ซึ่งอาจหลุดซ้ำอีกไม่จบไม่สิ้น
 * ส่งทีละก้อนทำให้เสียแค่ก้อนที่ค้าง แล้วต่อจากตรงนั้นได้
 *
 * ------------------------------------------------------------
 * โปรโตคอล
 * ------------------------------------------------------------
 *   action=status  upload_id            → คืน received = จำนวนไบต์ที่มีแล้ว
 *   action=chunk   upload_id offset      → ต่อก้อนที่ท้ายไฟล์ คืน received ใหม่
 *   action=finish  upload_id name size   → ตรวจขนาด แล้วส่งต่อ cd_guest_accept()
 *
 * **ก้อนต้องมาตามลำดับ** — ถ้า offset ที่ส่งมาไม่ตรงกับขนาดไฟล์ปัจจุบันเป๊ะ
 * จะถูกปฏิเสธพร้อมบอกว่าควรเริ่มที่ไบต์ไหน ไม่เขียนทับและไม่เว้นช่องว่าง
 * เพราะไฟล์ที่มีรูตรงกลางคือไฟล์เสียที่ตรวจไม่เจอจนกว่าจะมีคนเปิด
 *
 * ------------------------------------------------------------
 * ความปลอดภัย
 * ------------------------------------------------------------
 * ทุกด่านตรวจ (นามสกุล · MIME · เพดานขนาด · โควตา · ชื่อซ้ำ) อยู่ใน
 * cd_guest_accept() ตัวเดียวกับที่ upload.php ใช้ — ทางนี้จึงข้ามด่านไหนไม่ได้เลย
 * ตรวจ MIME ตอนไฟล์ประกอบเสร็จแล้วเท่านั้น ไม่ตรวจจากก้อนแรก
 */

require_once __DIR__ . '/../../config/customer_drive.php';

header('Referrer-Policy: no-referrer');

[$link, $session] = cd_guest_guard();

if ((string) $link['allow_upload'] !== '1') {
    cd_fail('ลิงก์นี้ไม่ได้เปิดให้ส่งไฟล์');
}

$storageError = cd_storage_error();

if ($storageError !== '') {
    error_log('portal upload_chunk: ' . $storageError);
    cd_fail('ระบบรับไฟล์ขัดข้องชั่วคราว กรุณาติดต่อผู้ตรวจสอบบัญชีของท่าน');
}

$action = (string) ($_POST['action'] ?? '');
$rawId  = (string) ($_POST['upload_id'] ?? '');

/*
 * upload_id มาจากฝั่งเบราว์เซอร์ จึงเชื่อไม่ได้ว่าเป็นอะไร —
 * บังคับให้เป็น hex 64 ตัวเท่านั้น (sha256) แล้วผูกกับ link_id ของรอบนี้อีกชั้น
 * เพื่อไม่ให้ใครเดา id ของคนอื่นแล้วต่อไฟล์เข้าไปในชิ้นส่วนของเขา
 */
if (!preg_match('/^[0-9a-f]{64}$/', $rawId)) {
    cd_fail('รหัสการอัปโหลดไม่ถูกต้อง');
}

$uploadId = hash('sha256', $rawId . '|' . (int) $link['link_id']);
$part = cd_chunk_path($uploadId);

// ------------------------------------------------------------ ถามว่ามีถึงไหนแล้ว

if ($action === 'status') {
    cd_chunk_sweep();

    cd_ok(['received' => is_file($part) ? (int) filesize($part) : 0]);
}

// ------------------------------------------------------------ รับก้อน

if ($action === 'chunk') {
    $offset = (int) ($_POST['offset'] ?? -1);
    $have = is_file($part) ? (int) filesize($part) : 0;

    /*
     * ไฟล์ใหญ่เกิน post_max_size ทำให้ PHP ทิ้งทั้ง body ก่อนโค้ดเราทำงาน
     * $_POST และ $_FILES จึงว่างพร้อมกันโดยไม่มี error
     */
    if (!$_POST && !$_FILES && (int) ($_SERVER['CONTENT_LENGTH'] ?? 0) > 0) {
        cd_fail('ก้อนข้อมูลใหญ่เกินกว่าที่เซิร์ฟเวอร์รับได้');
    }

    $file = $_FILES['chunk'] ?? null;

    if (!$file || !is_array($file) || ($file['error'] ?? UPLOAD_ERR_NO_FILE) !== UPLOAD_ERR_OK) {
        cd_fail('ไม่พบก้อนข้อมูลที่ส่งมา');
    }

    $tmp = (string) $file['tmp_name'];

    if (!is_uploaded_file($tmp)) {
        cd_fail('ก้อนข้อมูลไม่ถูกต้อง');
    }

    /*
     * ปฏิเสธถ้าลำดับไม่ตรง แล้ว**บอกไปด้วยว่าควรเริ่มที่ไหน**
     *
     * เกิดได้จริงเมื่อคำขอก่อนหน้าสำเร็จฝั่งเซิร์ฟเวอร์แต่คำตอบหายกลางทาง
     * ฝั่งเบราว์เซอร์จึงส่งก้อนเดิมซ้ำ — ถ้าเราเขียนทับ ไฟล์จะยาวเกินและเสีย
     * ถ้าตอบเฉย ๆ ว่าผิด ฝั่งเบราว์เซอร์จะไม่รู้ว่าต้องกระโดดไปไหน
     */
    if ($offset !== $have) {
        cd_json([
            'result'   => '4',
            'msn'      => 'ลำดับข้อมูลไม่ตรง กำลังส่งต่อจากจุดที่ถูกต้อง',
            'received' => $have,
        ]);
    }

    // กันไม่ให้ชิ้นส่วนโตเกินเพดานไฟล์ ก่อนที่จะเสียพื้นที่ดิสก์ไปแล้ว
    $max = cd_max_upload_bytes();

    if ($have + (int) $file['size'] > $max) {
        @unlink($part);
        cd_fail('ไฟล์ใหญ่เกิน ' . cd_format_bytes($max));
    }

    $in = @fopen($tmp, 'rb');
    $out = @fopen($part, $have === 0 ? 'wb' : 'ab');

    if (!$in || !$out) {
        if ($in) { fclose($in); }
        if ($out) { fclose($out); }

        error_log('portal upload_chunk: เปิดไฟล์เพื่อต่อก้อนไม่ได้ ' . $part);
        cd_fail('บันทึกข้อมูลไม่สำเร็จ กรุณาลองใหม่');
    }

    /*
     * ล็อกไฟล์ระหว่างเขียน — เบราว์เซอร์อาจยิงซ้ำตอนเน็ตกลับมา
     * ถ้าสองคำขอเขียนพร้อมกัน ไฟล์จะปนกันแบบที่ตรวจไม่เจอ
     */
    if (!flock($out, LOCK_EX)) {
        fclose($in);
        fclose($out);
        cd_fail('มีการส่งซ้อนกัน กรุณาลองใหม่');
    }

    stream_copy_to_stream($in, $out);

    fflush($out);
    flock($out, LOCK_UN);
    fclose($out);
    fclose($in);

    clearstatcache(true, $part);

    cd_ok(['received' => (int) filesize($part)]);
}

// ------------------------------------------------------------ ประกอบเสร็จ

if ($action === 'finish') {
    $name = (string) ($_POST['name'] ?? '');
    $size = (int) ($_POST['size'] ?? 0);

    if (!is_file($part)) {
        cd_fail('ไม่พบข้อมูลที่ส่งมา กรุณาส่งใหม่');
    }

    clearstatcache(true, $part);
    $have = (int) filesize($part);

    /*
     * ขนาดต้องตรงเป๊ะกับที่ประกาศไว้
     *
     * นี่คือด่านเดียวที่จับได้ว่าก้อนหายไปกลางทาง — ถ้าไม่ตรวจ ไฟล์ที่ขาด
     * จะเข้าระบบไปเงียบ ๆ แล้วพนักงานเปิดไม่ได้ในวันที่ต้องใช้จริง
     */
    if ($size <= 0 || $have !== $size) {
        @unlink($part);

        cd_json([
            'result' => '4',
            'msn'    => 'ข้อมูลไม่ครบ (ได้ ' . cd_format_bytes($have) . ' จาก ' . cd_format_bytes($size) . ') กรุณาส่งใหม่',
        ]);
    }

    /*
     * ส่งต่อให้ตรรกะร่วมตัวเดียวกับ upload.php
     *
     * cd_guest_accept() คัดลอกไฟล์ไปที่เก็บจริงด้วย cd_commit_version()
     * แล้วจบคำขอเอง ชิ้นส่วนจึงต้องถูกลบ **ก่อน** เรียก ไม่ได้ —
     * ลบทีหลังก็ไม่ได้เพราะฟังก์ชันไม่คืนค่ากลับมา
     *
     * ทางออกคือลงทะเบียนให้ลบตอนจบสคริปต์ ซึ่งทำงานทุกเส้นทางรวมถึงตอน cd_fail()
     */
    register_shutdown_function(static function () use ($part) {
        @unlink($part);
    });

    cd_guest_accept($link, $session, $part, $name);
}

cd_fail('คำสั่งไม่ถูกต้อง');
